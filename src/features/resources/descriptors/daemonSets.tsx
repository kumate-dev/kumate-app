const ownerSummary = (owners?: V1OwnerReference[]): string | undefined =>
  owners?.map((owner) => `${owner.kind}/${owner.name}`).join(', ');

const quantitySummary = (quantities?: { [key: string]: string }): string | undefined => {
  const entries = Object.entries(quantities ?? {});
  if (entries.length === 0) return undefined;
  return entries.map(([key, value]) => `${key} ${value}`).join(' · ');
};

const portSummary = (container: V1Container): string | undefined => {
  const ports = container.ports ?? [];
  if (ports.length === 0) return undefined;
  return ports.map((port) => `${port.containerPort}/${port.protocol ?? 'TCP'}`).join(', ');
};

/**
 * `key=value` pairs of the pod template's node selector, as one string.
 *
 * Feeds the column's `value`, which is why it is not a `LabelList`: chips in a 28px row
 * would mean one Kobalte tooltip root per label per visible row, the cost `StatusBadge`
 * documents avoiding. The column is `sortable: false`, so this is only ever called when
 * the search box is used — the full set is in the Pod template section either way.
 */
const nodeSelectorSummary = (daemonSet: V1DaemonSet): string | undefined => {
  const selector = daemonSet.spec?.template.spec?.nodeSelector;
  if (!selector) return undefined;
  const entries = Object.entries(selector);
  if (entries.length === 0) return undefined;
  return entries.map(([key, value]) => `${key}=${value}`).join(', ');
};

const strategySummary = (daemonSet: V1DaemonSet): string | undefined => {
  const strategy = daemonSet.spec?.updateStrategy;
  if (!strategy?.type) return undefined;
  if (strategy.type !== 'RollingUpdate') return strategy.type;

  const unavailable = strategy.rollingUpdate?.maxUnavailable ?? 1;
  const surge = strategy.rollingUpdate?.maxSurge;
  const surgePart = surge === undefined ? '' : `, max surge ${surge}`;
  return `RollingUpdate (max unavailable ${unavailable}${surgePart})`;
};

const selectorSummary = (daemonSet: V1DaemonSet): string | undefined => {
  const expressions = daemonSet.spec?.selector?.matchExpressions;
  if (!expressions || expressions.length === 0) return undefined;
  return expressions
    .map((expression) =>
      `${expression.key} ${expression.operator} ${expression.values?.join(',') ?? ''}`.trim()
    )
    .join(', ');
};

/**
 * Tolerations as `key operator value : effect`.
 *
 * Worth a row on this kind specifically: a DaemonSet that is expected to run on control
 * plane or tainted nodes and does not is almost always a missing toleration, and there is
 * nowhere else in the app to see them.
 */
const tolerationSummary = (daemonSet: V1DaemonSet): string | undefined => {
  const tolerations = daemonSet.spec?.template.spec?.tolerations;
  if (!tolerations || tolerations.length === 0) return undefined;
  return tolerations
    .map((toleration) => {
      const key = toleration.key ?? '*';
      const operator = toleration.operator ?? 'Equal';
      const value = toleration.value ? ` ${toleration.value}` : '';
      const effect = toleration.effect ? ` : ${toleration.effect}` : '';
      return `${key} ${operator}${value}${effect}`;
    })
    .join(', ');
};

const volumeNames = (daemonSet: V1DaemonSet): string | undefined => {
  const volumes = daemonSet.spec?.template.spec?.volumes;
  if (!volumes || volumes.length === 0) return undefined;
  return volumes.map((volume) => volume.name).join(', ');
};

/**
 * Init container names, as one line.
 *
 * Named rather than expanded into cards: node-level DaemonSets routinely use an init
 * container only to copy a binary onto the host, and a full card per one of those pushes
 * the container that does the work off the screen. The Pods screen shows their state.
 */
const initContainerNames = (daemonSet: V1DaemonSet): string | undefined => {
  const containers = daemonSet.spec?.template.spec?.initContainers;
  if (!containers || containers.length === 0) return undefined;
  return containers.map((container) => container.name).join(', ');
};

