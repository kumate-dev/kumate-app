/**
 * The state to show in the Status column.
 *
 * The hue mapping is the one from `utils/daemonSetStatus.ts` — all ready is `success`,
 * some ready is `warning`, none ready is `error`. What is new is that the three states a
 * ratio cannot express get to override it:
 *
 * - `desiredNumberScheduled === 0` is not a failure. It means the node selector matches
 *   nothing, which on a mixed-OS cluster is the normal state of half the DaemonSets in
 *   `kube-system`. The React version hued it `default` but still printed `0 / 0`, which
 *   reads as broken.
 * - `updatedNumberScheduled < desired` is a rollout in progress. Pods are ready, but they
 *   are not the pods the spec asks for.
 * - `numberMisscheduled > 0` means pods are running where they should not be. Nothing
 *   else on the screen says so.
 *
 * Written with plain field reads and no allocation: this runs per row per sort.
 */
export const getDaemonSetStatus = (daemonSet: V1DaemonSet): K8sStatus => {
  const status = daemonSet.status;
  const desired = status?.desiredNumberScheduled ?? 0;
  const ready = status?.numberReady ?? 0;

  if (desired === 0) return { status: 'No nodes matched', variant: 'secondary' };
  if (ready === 0) return { status: 'Unavailable', variant: 'error' };
  if (ready < desired) return { status: 'Progressing', variant: 'warning' };

  // Compared only when the field is present: `updatedNumberScheduled` is optional, and
  // treating a missing value as 0 would report a permanent rollout on any apiserver that
  // does not send it.
  const updated = status?.updatedNumberScheduled;
  if (updated !== undefined && updated < desired) {
    return { status: 'Rolling out', variant: 'warning' };
  }

  if ((status?.numberMisscheduled ?? 0) > 0) return { status: 'Misscheduled', variant: 'warning' };

  return { status: 'Available', variant: 'success' };
};

