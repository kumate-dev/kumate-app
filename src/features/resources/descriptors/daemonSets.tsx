/**
 * DaemonSets.
 *
 * Two departures from the React original, both of which it got wrong:
 *
 * - **Status is a word, not a ratio.** `utils/daemonSetStatus.ts` returned
 *   `"2 / 3"` as the *status string* and hued it. That is the Ready column's job, and it
 *   left the DaemonSet-specific failure — pods running on nodes the selector no longer
 *   matches, i.e. `numberMisscheduled` — with nowhere to appear at all. A DaemonSet whose
 *   selector was edited reads as perfectly healthy in the React table.
 * - **There is no Scale action.** A DaemonSet has no `spec.replicas`; its replica count
 *   *is* the number of matching nodes. `api/k8s/daemonSets.ts` exports `scaleDaemonSet`
 *   and the backend registers `scale_daemon_set` — both generated by the macro that also
 *   covers Deployments — and calling either would patch a field the apiserver does not
 *   recognise on this kind. It is deliberately not wired up here. To change how many pods
 *   a DaemonSet runs you edit `spec.template.spec.nodeSelector`, which is what the Node
 *   selector column and the Pod template section are for.
 */

